#Function to generate the story using gemma4:e4b
def get_story(screen):
    clock=pygame.time.Clock()
    result={"story": None}
    #Model being used 
    MODEL="gemma4:e4b"
    
    def worker():
        #Prompt generated by claude ai
        CHAT_PROMPT="""Write a spooky 5-sentence Halloween story for a Mad Libs game.

Use exactly 8 blanks. Each blank must be one of these labels, written in curly braces:
{noun}, {plural noun}, {adjective}, {adverb}, {place}, {animal},
{verb}, {past tense verb}, {verb ending in -ing}

Rules:
- Every blank contains ONLY a label from the list above, never a real word from the story.
- Write the grammar around each blank so it fits that label. {verb} follows "to" or "will" (to {verb}),
  {past tense verb} is for things that already happened (she {past tense verb}),
  and {verb ending in -ing} follows "was" or "is" (he was {verb ending in -ing}).
- Do not repeat a label more than twice.
- Output only the story. No title, no intro, no notes.

Example:
The {adjective} {noun} was {verb ending in -ing} near the old {place}. Everyone had {past tense verb} away, but Mia decided to {verb}.
"""
        try:
            #Generates a response based on the prompt
            response=ollama.chat(
                model=MODEL,
                messages=[{"role": "user", "content": CHAT_PROMPT}],
            )
            result["story"]=response["message"]["content"]
        except Exception as e:
            #Alert if there is an error in generation 
            print("Something went wrong:", e)
            result["story"]=""
    #Starts the generation, as designates it as a backround daemon thread
    thread=threading.Thread(target=worker, daemon=True)
    thread.start()

    #Dots that will appear whilst the story is generating
    dots=0
    last_tick=pygame.time.get_ticks()
    #While the daemon thread is generating the text
    while thread.is_alive():
        check_events()
        #Finds the time between the last dot being added and then adds a dot if enough frames have passed
        now=pygame.time.get_ticks()
        if now - last_tick > 500:      
            dots=(dots + 1) % 4
            last_tick=now
        #Displays text to inform user
        draw_background(screen)
        draw_text("Generating SpOoKy StOrY" + "." * dots, 40, (640, 360))
        pygame.display.update()
        clock.tick(30)

    return result["story"]

