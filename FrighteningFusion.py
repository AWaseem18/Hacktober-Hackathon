#Function to strip the story into an array of text prompts
def get_text_array(text):
    out_arr=re.findall(r"\{(.*?)\}", text)
    return out_arr

#Function that fills the story with the inputted text
def fill_story(story, answers):
    answers=iter(answers)
    return re.sub(r"\{.*?\}", lambda m: next(answers), story)

#Function that wraps the text if it is too long
def wrap_text(text, size, max_width):
    font=pygame.font.Font("fonts/THE-MONSTOR.ttf", size)
    lines, line=[], ""
    for word in text.split():
        test=(line + " " + word).strip()
        if font.size(test)[0] <= max_width:
            line=test
        else:
            lines.append(line)
            line=word
    if line:
        lines.append(line)
    return lines

#Function that resets the engine each sentance because pyttsx3 is wierd
def speak(text):
    engine=pyttsx3.init()
    rate=engine.getProperty('rate')
    engine.setProperty('rate', rate - 50)  
    engine.setProperty('volume', 1)  
    voices=engine.getProperty('voices')
    engine.setProperty('voice', voices[1].id)
    engine.say(text)
    engine.runAndWait()
    del engine

#Function that shows the story to the user
def show_story(screen, story):
    clock=pygame.time.Clock()
    
    #Splits up the story into explicit sentances
    sentences=re.split(r"(?<=[.!?])\s+", story.strip())
    #Tracks what sentance has been spoken so the tts doesnt overlay
    spoke=-1
    i=0
    while i < len(sentences):
        for event in pygame.event.get():
            if event.type==pygame.QUIT:
                pygame.quit()
                sys.exit()
            #Goes to the next sentance 
            if event.type==pygame.KEYDOWN and event.key in (pygame.K_RETURN,pygame.K_SPACE):
                i+=1
        #Stops when the sentances are done
        if i >= len(sentences):
            break

        #Draws background
        draw_background(screen)

        #Draws the sentance ensuring it doesnt go too far
        lines=wrap_text(sentences[i],40,1000)
        y=360-(len(lines)-1)*25     
        #gives the line number and the line it self to be drawn onto the screen
        for n,line in enumerate(lines):
            draw_text(line,40,(640,y+n*50))
        
        draw_text("Press Enter to continue", 25, (640, 680))

        pygame.display.update()
        #Ensures the speak func isnt ran multiple times
        if spoke!=i:
            spoke=i
            speak(sentences[i])
            pygame.event.clear()

        clock.tick(30)

